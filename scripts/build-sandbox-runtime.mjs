import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const outDir = path.join(rootDir, 'src', 'sandbox', 'generated');
const outFile = path.join(outDir, 'reactRuntime.ts');

async function main() {
  fs.mkdirSync(outDir, { recursive: true });

  const result = await build({
    stdin: {
      contents: `
        import * as React from 'react';
        import * as ReactDOMClient from 'react-dom/client';
        window.React = React;
        window.ReactDOMClient = ReactDOMClient;
        window.ReactDOM = ReactDOMClient;
      `,
      resolveDir: rootDir,
      loader: 'js',
    },
    bundle: true,
    write: false,
    format: 'iife',
    platform: 'browser',
    target: ['es2020'],
    minify: true,
    define: {
      'process.env.NODE_ENV': '"production"',
    },
  });

  const bundledCode = result.outputFiles[0].text;
  const tsSource = `// Auto-generated by scripts/build-sandbox-runtime.mjs — do not edit manually.\nexport const REACT_RUNTIME_IIFE = ${JSON.stringify(bundledCode)};\n`;
  fs.writeFileSync(outFile, tsSource, 'utf8');
  console.log(`Built offline React 19 sandbox runtime (${(bundledCode.length / 1024).toFixed(1)} KB) -> src/sandbox/generated/reactRuntime.ts`);
}

main().catch((err) => {
  console.error('Failed to build sandbox runtime:', err);
  process.exit(1);
});
